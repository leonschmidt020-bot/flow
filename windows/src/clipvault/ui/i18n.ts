export type StringKey = Keys;

export function tr(locale: 'de' | 'en', key: Keys, ...args: (string | number)[]): string {
  let s = (locale === 'en' ? en : de)[key] ?? de[key] ?? key;
  args.forEach((a, i) => { s = s.replace(`{${i}}`, String(a)); });
  return s;
}
