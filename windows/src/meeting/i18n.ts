const dicts: Record<MLoc, Dict> = { de, en };

export function mt(loc: MLoc, key: MKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[loc]?.[key] ?? de[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** progress note keys stored in meeting.json → text; unknown notes (error messages) pass through */
export function noteText(loc: MLoc, note: string | undefined): string {
  if (!note) return '';
  const k = `st_${note}` as MKey;
  return k in de ? mt(loc, k) : note;
}

export const _mdicts = dicts;
