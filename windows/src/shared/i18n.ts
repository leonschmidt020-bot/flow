const dicts: Record<Locale, Dict> = { de, en };

export function t(locale: Locale, key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[locale]?.[key] ?? de[key] ?? String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function hotkeyName(locale: Locale, hk: string): string {
  if (hk.startsWith('F')) return hk;
  const k = `hk_${hk}` as I18nKey;
  return t(locale, k);
}

/** short name for toasts/status */
export function hotkeyShort(locale: Locale, hk: string): string {
  if (hk === 'RightCtrl') return locale === 'de' ? 'rechte Strg' : 'Right Ctrl';
  if (hk === 'CtrlWin') return locale === 'de' ? 'Strg + Win' : 'Ctrl + Win';
  if (hk === 'RightAlt') return 'Alt Gr';
  return hk;
}

